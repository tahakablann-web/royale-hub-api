export function getFourCardCycleElixir(cards) {
  if (!cards || cards.length < 4) return 0;
  const sorted = [...cards].sort((a, b) => (a.elixir || 3) - (b.elixir || 3));
  return sorted.slice(0, 4).reduce((sum, c) => sum + (c.elixir || 3), 0);
}

