function enrichCardForAnalysis(card) {
  const local =
    ALL_CARDS_LIST.find((lc) => lc.id === card.id) ||
    ALL_CARDS_LIST.find(
      (lc) =>
        (card.nameEn && lc.nameEn.toLowerCase() === card.nameEn.toLowerCase()) ||
        (card.name && lc.nameEn.toLowerCase() === card.name.toLowerCase())
    );
  const enName = local?.nameEn || card.nameEn || card.name || '';
  const roles = new Set([...(local?.role || []), ...(card.role || [])]);
  Object.entries(ROLE_SETS).forEach(([roleKey, nameSet]) => {
    if (nameSet.has(enName)) roles.add(roleKey);
  });
  if (card.rarity === 'Şampiyon' || card.rarity === 'champion') roles.add('champion');
  const roleArr = Array.from(roles);
  const isAirUnit = roleArr.includes('air_def');
  return {
    ...card,
    elixir: card.elixir || local?.elixir || 3,
    role: roleArr,
    attack: local?.attack || (roleArr.includes('win_cond') ? 92 : 76),
    defense: local?.defense || (roleArr.includes('tank_killer') || isAirUnit ? 88 : 76),
    air: local?.air || (isAirUnit ? 85 : 0),
  };
}

export function analyzeCustomDeck(deckCards, lang = 'tr') {
  const isEn = lang === 'en';
  if (!deckCards || deckCards.length === 0) {
    return {
      avgElixir: '0.0',
      fourCardCycle: 0,
      attackScore: 0,
      defenseScore: 0,
      airScore: 0,
      synergyScore: 0,
      grade: '-',
      archetype: isEn ? 'Select 8 Cards' : '8 Kart Seç',
      spellCount: 0,
      championCount: 0,
      evoReadyCount: 0,
      roleChecks: [
        { id: 'win_cond', label: isEn ? '🎯 Win Condition' : '🎯 Kule Yıkıcı', ok: false },
        { id: 'air_def', label: isEn ? '🛡️ Air Defense (2+)' : '🛡️ Hava Savunma (2+)', ok: false },
        { id: 'tank_killer', label: isEn ? '⚔️ Tank Killer' : '⚔️ Tank Eritici', ok: false },
        { id: 'small_spell', label: isEn ? '💥 Small Spell' : '💥 Küçük Büyü', ok: false },
        { id: 'big_spell', label: isEn ? '🔥 Big Spell' : '🔥 Büyük Büyü', ok: false },
        { id: 'reset', label: isEn ? '⚡ Reset Card' : '⚡ Sıfırlayıcı (Reset)', ok: false },
        { id: 'splash', label: isEn ? '🌪️ Splash Control' : '🌪️ Alan Hasarı (Splash)', ok: false },
        { id: 'building', label: isEn ? '🏰 Building / Pull' : '🏰 Bina / Dikkat Dağıtıcı', ok: false },
      ],
      warnings: [
        isEn
          ? 'Pick 8 cards from the card pool below for a complete Clash Royale Deck Check!'
          : 'Kapsamlı Clash Royale Deste Analizi için aşağıdan 8 kart seç!',
      ],
      strengths: [],
    };
  }

  const enriched = deckCards.map(enrichCardForAnalysis);
  const totalElixir = enriched.reduce((acc, c) => acc + (c.elixir || 3), 0);
  const avgNum = totalElixir / enriched.length;
  const avgElixir = avgNum.toFixed(1);
  const fourCardCycle = getFourCardCycleElixir(enriched);

  const avgAttack = Math.round(
    enriched.reduce((acc, c) => acc + (c.attack || 75), 0) / enriched.length
  );
  const avgDefense = Math.round(
    enriched.reduce((acc, c) => acc + (c.defense || 75), 0) / enriched.length
  );
  const airCards = enriched.filter(
    (c) => (c.air || 0) >= 65 || (c.role || []).includes('air_def')
  );
  const airScore = Math.min(100, Math.round((airCards.length / 3) * 85 + 15));

  const hasWinCond = enriched.some((c) => (c.role || []).includes('win_cond'));
  const hasSmallSpell = enriched.some((c) => (c.role || []).includes('small_spell'));
  const hasBigSpell = enriched.some((c) => (c.role || []).includes('big_spell'));
  const hasTankKiller = enriched.some((c) => (c.role || []).includes('tank_killer'));
  const hasReset = enriched.some((c) => (c.role || []).includes('reset'));
  const hasAirDef = airCards.length >= 2;
  const hasSplash = enriched.some((c) => (c.role || []).includes('splash'));
  const hasBuilding = enriched.some((c) => (c.role || []).includes('building'));

  const spellCards = enriched.filter(
    (c) => (c.role || []).includes('small_spell') || (c.role || []).includes('big_spell')
  );
  const championCount = enriched.filter((c) => (c.role || []).includes('champion')).length;
  const evoReadyCount = enriched.filter((c) => c.evo).length;
  const cycleCount = enriched.filter((c) => (c.role || []).includes('cycle')).length;

  const roleChecks = [
    { id: 'win_cond', label: isEn ? '🎯 Win Condition' : '🎯 Kule Yıkıcı', ok: hasWinCond },
    { id: 'air_def', label: isEn ? '🛡️ Air Defense (2+)' : '🛡️ Hava Savunma (2+)', ok: hasAirDef },
    { id: 'tank_killer', label: isEn ? '⚔️ Tank Killer' : '⚔️ Tank Eritici', ok: hasTankKiller },
    { id: 'small_spell', label: isEn ? '💥 Small Spell' : '💥 Küçük Büyü', ok: hasSmallSpell },
    { id: 'big_spell', label: isEn ? '🔥 Big Spell' : '🔥 Büyük Büyü', ok: hasBigSpell },
    { id: 'reset', label: isEn ? '⚡ Reset Card' : '⚡ Sıfırlayıcı (Reset)', ok: hasReset },
    { id: 'splash', label: isEn ? '🌪️ Splash Control' : '🌪️ Alan Hasarı (Splash)', ok: hasSplash },
    { id: 'building', label: isEn ? '🏰 Building / Pull' : '🏰 Bina / Savunma', ok: hasBuilding },
  ];

  const passedCount = roleChecks.filter((r) => r.ok).length;
  let synergyScore = 54 + passedCount * 5;
  if (spellCards.length >= 2 && spellCards.length <= 3) synergyScore += 5;
  if (evoReadyCount >= 1) synergyScore += 2;
  if (championCount > 1) synergyScore -= 18;
  synergyScore = Math.max(30, Math.min(99, synergyScore));

  let grade = 'B';
  if (passedCount >= 8 && synergyScore >= 92 && championCount <= 1) grade = 'S+';
  else if (passedCount >= 7 && synergyScore >= 85 && championCount <= 1) grade = 'S';
  else if (passedCount >= 5 && championCount <= 1) grade = 'A';
  else if (passedCount <= 3 || championCount > 1) grade = 'C';

  const namesEn = new Set(enriched.map((c) => c.nameEn));
  let archetype = isEn ? '⚖️ Balanced Control' : '⚖️ Dengeli Kontrol';
  if (namesEn.has('X-Bow') || namesEn.has('Mortar')) {
    archetype = isEn ? '🎯 Siege (X-Bow / Mortar)' : '🎯 Kuşatma (Siege)';
  } else if (namesEn.has('Golem') || namesEn.has('Lava Hound') || namesEn.has('Electro Giant') || avgNum >= 4.2) {
    archetype = isEn ? '🏰 Heavy Beatdown' : '🏰 Ağır Tank (Beatdown)';
  } else if (namesEn.has('Goblin Barrel') || namesEn.has('Skeleton Barrel') || namesEn.has('Princess')) {
    archetype = isEn ? '💣 Log Bait / Swarm Bait' : '💣 Büyü Yemleme (Bait)';
  } else if (namesEn.has('P.E.K.K.A') || namesEn.has('Battle Ram') || namesEn.has('Bandit') || namesEn.has('Ram Rider')) {
    archetype = isEn ? '⚔️ Bridge Spam' : '⚔️ Köprü Baskısı (Bridge Spam)';
  } else if (avgNum <= 3.1 || cycleCount >= 4) {
    archetype = isEn ? '⚡ Fast Cycle' : '⚡ Hızlı Döngü (Fast Cycle)';
  }

  const warnings = [];
  const strengths = [];

  if (deckCards.length < 8) {
    warnings.push(
      isEn
        ? `ℹ️ Deck incomplete (${deckCards.length}/8): Add ${8 - deckCards.length} more card(s) to finish.`
        : `ℹ️ Destede ${deckCards.length}/8 kart var: Tam analiz için ${8 - deckCards.length} kart daha ekle.`
    );
  }

  if (championCount > 1) {
    warnings.push(
      isEn
        ? `🚨 Invalid Rule: Clash Royale allows max 1 Champion per deck (you picked ${championCount}).`
        : `🚨 Oyun Kuralı Uyarısı: Bir destede en fazla 1 Şampiyon bulunabilir (şu an ${championCount} seçili).`
    );
  } else if (championCount === 1) {
    strengths.push(
      isEn
        ? '👑 3-Card Cycle Ready: Having 1 Champion boosts defensive ability & faster card cycling.'
        : '👑 Şampiyon Avantajı: Şampiyon hayattayken 3 kart döngüsü ile hızlı savunma kurabilirsin.'
    );
  }

  if (!hasWinCond) {
    warnings.push(
      isEn
        ? '⚠️ Missing Win Condition: Add a tower-targeting card (Hog Rider, Battle Ram, Barrel, Royal Giant, or Balloon).'
        : '⚠️ Kule Yıkıcı Eksik: Doğrudan kuleyi hedef alan bir kart (Domuz, Koçbaşı, Fıçı, Kraliyet Devi, Balon) eklemelisin.'
    );
  } else {
    strengths.push(
      isEn
        ? '✅ Solid Win Condition ready to apply consistent tower pressure.'
        : '✅ Kule baskısı kurabilecek net bir saldırı kartın var.'
    );
  }

  if (!hasAirDef) {
    warnings.push(
      isEn
        ? '⚠️ Weak Air Defense: Include at least 2 air-targeting cards against Balloon and LavaLoon.'
        : '⚠️ Hava Savunması Zayıf: Balon veya Lav Tazısına karşı en az 2 hava vuran kart önerilir.'
    );
  } else {
    strengths.push(
      isEn
        ? `✅ Strong air coverage (${airCards.length} air-capable cards) against Balloon & LavaLoon.`
        : `✅ Güçlü hava savunması (${airCards.length} kart): Balon ve Lav Tazısına karşı güvendesin.`
    );
  }

  if (!hasTankKiller) {
    warnings.push(
      isEn
        ? '⚠️ Missing Tank Killer: Add Mini P.E.K.K.A, P.E.K.K.A, or Inferno Dragon/Tower to stop heavy tanks.'
        : '⚠️ Tank Eritici Eksik: Mega Şövalye, P.E.K.K.A veya Golem eritmek için Mini P.E.K.K.A, P.E.K.K.A veya Cehennem Ejderhası/Kulesi önerilir.'
    );
  }

  if (!hasSmallSpell) {
    warnings.push(
      isEn
        ? '⚠️ Missing Small Spell: Add The Log, Arrows, or Zap to clear swarms.'
        : '⚠️ Küçük Büyü Eksik: Goblin Fıçısı / İskelet Ordusu için Tomruk, Oklar veya Çarpma ekle.'
    );
  }

  if (!hasBigSpell) {
    warnings.push(
      isEn
        ? '⚠️ No Heavy Spell: Fireball, Poison, or Lightning helps finish low-HP towers and clear support units.'
        : '⚠️ Büyük Büyü Eksik: Maç sonunda kule bitirmek ve destek birliklerini eritmek için Alev Topu, Zehir veya Yıldırım önerilir.'
    );
  }

  if (!hasReset) {
    warnings.push(
      isEn
        ? '⚠️ No Reset Card: Inferno Tower/Dragon and Sparky can punish decks without Zap, E-Wiz, or E-Spirit.'
        : '⚠️ Sıfırlayıcı Eksik: Cehennem Kulesi, Cehennem Ejderhası ve Kıvılcım’ı sıfırlamak için Çarpma, E-Ruh veya Elektro Büyücü yararlı olur.'
    );
  }

  if (!hasSplash) {
    warnings.push(
      isEn
        ? '⚠️ Low Splash Damage: Against swarm pushes (Goblin Gang, Bats, Recruits), add Valkyrie, Bomber, Baby Dragon, or Arrows.'
        : '⚠️ Alan Hasarı Düşük: İskelet Ordusu / Yarasa sürülerine karşı Valkür, Bombacı, Yavru Ejderha veya Oklar eklemen faydalı olur.'
    );
  } else {
    strengths.push(
      isEn
        ? '✅ Swarm control & splash damage coverage is balanced.'
        : '✅ Sürü kartlara karşı alan hasarı (Splash) savunman dengeli.'
    );
  }

  if (hasBuilding) {
    strengths.push(
      isEn
        ? '✅ Defensive building pulls Hog Rider, Ram Rider, and Giant safely to the center.'
        : '✅ Savunma binası ile Domuz Binicisi, Koç Binicisi ve Dev gibi kartları ortaya çekebilirsin.'
    );
  }

  if (spellCards.length >= 4) {
    warnings.push(
      isEn
        ? `⚠️ Too Many Spells (${spellCards.length}): Keep 2–3 spells max so you have enough troops on the arena.`
        : `⚠️ Fazla Büyü (${spellCards.length} Büyü): Sahada asker üstünlüğü kurmak için destede genelde 2–3 büyü yeterlidir.`
    );
  }

  if (avgNum > 4.3) {
    warnings.push(
      isEn
        ? `Heavy Elixir (${avgElixir}): Defend carefully in 1x Elixir and build pushes in 2x Elixir.`
        : `Ağır İksir (${avgElixir}): Tekli iksirde savunmada kalıp ikili iksiri beklemelisin.`
    );
  } else if (avgNum <= 3.4) {
    strengths.push(
      isEn
        ? `⚡ Fast Cycle (${avgElixir} Avg | 4-Card Cycle: ${fourCardCycle} Elixir): Out-cycle your opponent's counters.`
        : `⚡ Hızlı Döngü (${avgElixir} Ort. | 4-Kart Döngüsü: ${fourCardCycle} İksir): Rakibinden hızlı kart çevirebilirsin.`
    );
  }

  return {
    avgElixir,
    fourCardCycle,
    attackScore: Math.min(99, avgAttack + 10),
    defenseScore: Math.min(99, avgDefense + 8),
    airScore,
    synergyScore,
    grade,
    archetype,
    spellCount: spellCards.length,
    championCount,
    evoReadyCount,
    roleChecks,
    warnings,
    strengths,
  };
}

export function getCardMatchupInfo(card, lang = 'tr') {
  if (!card) return null;
  const isEn = lang === 'en';
  const c = enrichCardForAnalysis(card);
  const roles = c.role || [];
  const roleLabels = [];
  if (roles.includes('win_cond')) roleLabels.push(isEn ? '🎯 Win Condition' : '🎯 Kule Yıkıcı');
  if (roles.includes('tank_killer')) roleLabels.push(isEn ? '⚔️ Tank Killer' : '⚔️ Tank Eritici');
  if (roles.includes('air_def')) roleLabels.push(isEn ? '🛡️ Air Defense' : '🛡️ Hava Savunması');
  if (roles.includes('small_spell')) roleLabels.push(isEn ? '💥 Small Spell' : '💥 Küçük Büyü');
  if (roles.includes('big_spell')) roleLabels.push(isEn ? '🔥 Big Spell' : '🔥 Büyük Büyü');
  if (roles.includes('reset')) roleLabels.push(isEn ? '⚡ Reset / Stun' : '⚡ Sıfırlayıcı');
  if (roles.includes('splash')) roleLabels.push(isEn ? '🌪️ Splash Area' : '🌪️ Alan Hasarı');
  if (roles.includes('building')) roleLabels.push(isEn ? '🏰 Building' : '🏰 Savunma Binası');
  if (roles.includes('champion')) roleLabels.push(isEn ? '👑 Champion' : '👑 Şampiyon');
  if (roleLabels.length === 0) roleLabels.push(isEn ? '⚔️ Support Troop' : '⚔️ Destek / Savaş Kartı');

  const strongAgainst = [];
  const weakAgainst = [];
  if (roles.includes('win_cond')) {
    strongAgainst.push(isEn ? 'Low-HP Towers, Unprepared Cycles' : 'Savunması eksik kuleler, yavaş döngüler');
    weakAgainst.push(isEn ? 'Buildings (Cannon/Tesla), Tank Killers' : 'Savunma Binaları (Top/Tesla), Tank Eriticiler');
  }
  if (roles.includes('tank_killer')) {
    strongAgainst.push(isEn ? 'P.E.K.K.A, Golem, Mega Knight, Giant' : 'Golem, Mega Şövalye, Dev, Kraliyet Devi');
    weakAgainst.push(isEn ? 'Swarms (Skeleton Army, Goblin Gang)' : 'Sürü Kartlar (İskelet Ordusu, Goblin Çetesi)');
  }
  if (roles.includes('splash') || roles.includes('small_spell')) {
    strongAgainst.push(isEn ? 'Goblin Barrel, Skeletons, Bats, Minions' : 'Goblin Fıçısı, İskeletler, Yarasalar, Minyonlar');
    weakAgainst.push(isEn ? 'High-HP Tanks & Mini Tanks (Knight, Valkyrie)' : 'Yüksek Canlı Tanklar (Şövalye, Dev, Golem)');
  }
  if (roles.includes('air_def')) {
    strongAgainst.push(isEn ? 'Balloon, Lava Hound, Baby Dragon, Phoenix' : 'Balon, Lav Tazısı, Yavru Ejderha, Anka');
    weakAgainst.push(isEn ? 'Heavy Spells (Fireball/Lightning/Poison)' : 'Büyük Büyüler (Alev Topu, Yıldırım, Zehir)');
  }
  if (roles.includes('building')) {
    strongAgainst.push(isEn ? 'Hog Rider, Ram Rider, Balloon, Giant' : 'Domuz Binicisi, Koç Binicisi, Balon, Dev');
    weakAgainst.push(isEn ? 'Earthquake, Lightning, Poison, Royal Giant' : 'Deprem, Yıldırım, Zehir, Kraliyet Devi');
  }
  if (strongAgainst.length === 0) {
    strongAgainst.push(isEn ? 'Mid-elixir ground pushes & counter-attacks' : 'Orta iksirli kara saldırıları ve karşı ataklar');
  }
  if (weakAgainst.length === 0) {
    weakAgainst.push(isEn ? 'Heavy Spell value & Swarm distraction' : 'Büyük büyü hasarı ve sürü dikkat dağıtıcılar');
  }

  return {
    ...c,
    roleLabels,
    strongAgainst,
    weakAgainst,
  };
}
