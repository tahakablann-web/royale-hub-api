export function completeDeckWithAI(currentCards) {
  const result = [...currentCards];
  const hasId = (id) => result.some((c) => c.id === id);
  const hasRole = (role) => result.some((c) => (c.role || []).includes(role));

  const priorityPool = [
    { role: 'win_cond', candidates: [CARDS.hog_rider, CARDS.battle_ram, CARDS.ram_rider, CARDS.royal_giant, CARDS.goblin_barrel] },
    { role: 'small_spell', candidates: [CARDS.the_log, CARDS.zap, CARDS.barbarian_barrel, CARDS.arrows] },
    { role: 'big_spell', candidates: [CARDS.fireball, CARDS.poison, CARDS.lightning] },
    { role: 'air_def', candidates: [CARDS.electro_wizard, CARDS.musketeer, CARDS.phoenix, CARDS.inferno_dragon, CARDS.magic_archer] },
    { role: 'tank_killer', candidates: [CARDS.pekka, CARDS.mini_pekka, CARDS.inferno_dragon, CARDS.inferno_tower, CARDS.prince] },
    { role: 'reset', candidates: [CARDS.zap, CARDS.electro_wizard, CARDS.electro_spirit, CARDS.lightning] },
    { role: 'cycle', candidates: [CARDS.ice_spirit, CARDS.electro_spirit, CARDS.skeletons, CARDS.ice_golem] },
  ];

  for (const group of priorityPool) {
    if (result.length >= 8) break;
    if (!hasRole(group.role)) {
      const pick = group.candidates.find((c) => !hasId(c.id));
      if (pick) result.push(pick);
    }
  }

  for (const fallback of ALL_CARDS_LIST) {
    if (result.length >= 8) break;
    if (!hasId(fallback.id)) {
      result.push(fallback);
    }
  }

  return result.slice(0, 8);
}

